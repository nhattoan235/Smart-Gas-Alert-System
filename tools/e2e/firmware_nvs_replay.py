def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


class Blocked(RuntimeError):
    """A required host/simulator capability was not available."""


class SerialTransportBlocked(Blocked):
    """The simulator serial transport could not be used for this run."""


class SerialWriteTimeout(SerialTransportBlocked):
    """A serial write exceeded its application-level deadline."""


class RuntimeLog:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.live_path = root / "nvs-replay-live.log"
        self.timeline_path = root / "nvs-runtime-timeline.csv"
        self.payload_path = root / "nvs-runtime-payloads.jsonl"
        self._lock = threading.RLock()
        self.timeline: list[dict] = []

    def write(self, stage: str, **fields: object) -> None:
        record = {"timestamp_utc": utc_now(), "stage": stage, **fields}
        line = json.dumps(record, separators=(",", ":"), ensure_ascii=True)
        with self._lock:
            self.live_path.parent.mkdir(parents=True, exist_ok=True)
            with self.live_path.open("a", encoding="utf-8") as output:
                output.write(line + "\n")
            self.timeline.append(record)
        print(line, flush=True)

    def payload(self, stage: str, identity: dict, raw: bytes) -> str:
        digest = hashlib.sha256(raw).hexdigest()
        try:
            payload = json.loads(raw)
        except (ValueError, UnicodeDecodeError):
            payload = None
        record = {
            "timestamp_utc": utc_now(), "stage": stage, **identity,
            "payload_sha256": digest, "payload": payload,
        }
        with self._lock:
            with self.payload_path.open("a", encoding="utf-8") as output:
                output.write(json.dumps(record, separators=(",", ":"), ensure_ascii=True) + "\n")
        return digest

    def save_timeline(self) -> None:
        columns = ["timestamp_utc", "stage", "device_id", "boot_id", "seq",
                   "queue_count", "payload_sha256", "detail"]
        with self.timeline_path.open("w", encoding="utf-8-sig", newline="") as output:
            writer = csv.DictWriter(output, fieldnames=columns, extrasaction="ignore")
            writer.writeheader()
            writer.writerows(self.timeline)


class RFC2217DiagnosticHandler(logging.Handler):
    """Persist pySerial's negotiation trace beside the runtime timeline."""

    _credential_pattern = re.compile(
        r"(?i)\b(password|token|secret|authorization)(\s*[:=]\s*)[^\s,;]+"
    )

    def __init__(self, runtime_log: RuntimeLog) -> None:
        super().__init__(logging.DEBUG)
        self.runtime_log = runtime_log

    def emit(self, record: logging.LogRecord) -> None:
        try:
            message = self._credential_pattern.sub(r"\1\2<redacted>", record.getMessage())
            self.runtime_log.write(
                "rfc2217_diagnostic",
                level=record.levelname,
                detail=message[:600],
            )
        except Exception:
            self.handleError(record)


def enable_rfc2217_diagnostics(runtime_log: RuntimeLog):
    """Capture only pySerial RFC2217 messages and return a logger restore callback."""
    logger = logging.getLogger("pySerial.rfc2217")
    previous_level = logger.level
    previous_propagate = logger.propagate
    handler = RFC2217DiagnosticHandler(runtime_log)
    logger.setLevel(logging.DEBUG)
    logger.propagate = False
    logger.addHandler(handler)

    def restore() -> None:
        logger.removeHandler(handler)
        handler.close()
        logger.setLevel(previous_level)
        logger.propagate = previous_propagate

    return restore


def parse_event_diag(line: str) -> dict | None:
    match = re.search(
        r"event_diag device_id=(\S+) boot_id=(\S+) seq=(\d+) identity=(\S+) "
        r"millis=(\d+) stage=(\S+) outcome=(\S+) queue_count=(\d+) "
        r"packet_id=(\d+) detail=(\S+)", line,
    )
    if not match:
        return None
    names = ("device_id", "boot_id", "seq", "identity", "millis", "stage",
             "outcome", "queue_count", "packet_id", "detail")
    record = dict(zip(names, match.groups()))
    for key in ("seq", "millis", "queue_count", "packet_id"):
        record[key] = int(record[key])
    return record


def parse_status(line: str) -> dict | None:
    if "nvs_test_status " not in line:
        return None
    fields = dict(re.findall(r"(\w+)=([^\s]+)", line.split("nvs_test_status ", 1)[1]))
    required = {"device_id", "boot_id", "seq", "queue_count", "mqtt_connected",
                "lpg_override", "red_pin", "buzzer_duty"}
    if not required.issubset(fields):
        return None
    for key in ("seq", "queue_count", "mqtt_connected", "lpg_override", "red_pin", "buzzer_duty"):
        fields[key] = int(fields[key])
    for key in ("lpg_invalid_test", "co_invalid_test"):
        if key in fields:
            fields[key] = int(fields[key])
    return fields


def validate_pending_queue_after_reboot(status: dict, previous_boot_id: str,
                                        expected_queue_count: int) -> int:
    """Validate persistent queue state without expecting RAM test controls to persist."""
    if status.get("boot_id") == previous_boot_id:
        raise AssertionError("firmware boot_id did not change after ESP.restart")
    actual_count = status.get("queue_count")
    if actual_count != expected_queue_count:
        raise AssertionError(
            f"NVS queue count changed across reboot: {expected_queue_count} -> {actual_count}"
        )
    # lpg_override is a test-only RAM control. It may reset with the MCU; the
    # queued event identity/payload and queue metadata are the persistence contract.
    return int(status.get("lpg_override", -1))


class SerialLineTooLong(ValueError):
    """A serial line exceeded the bounded framing buffer without a newline."""


def extract_complete_serial_lines(pending: bytearray, chunk: bytes,
                                  max_line_bytes: int = MAX_SERIAL_LINE_BYTES) -> list[bytes]:
    """Append a serial read chunk and return only newline-terminated lines.

    RFC2217 reads may return a partial line when the configured read timeout
    expires. Keep that fragment until a later read supplies the rest instead
    of treating each read result as a complete firmware log record.
    """
    pending.extend(chunk)
    complete: list[bytes] = []
    while True:
        newline = pending.find(b"\n")
        if newline < 0:
            if len(pending) > max_line_bytes:
                raise SerialLineTooLong(
                    f"serial line exceeded {max_line_bytes} bytes without newline"
                )
            break
        if newline > max_line_bytes:
            raise SerialLineTooLong(
                f"serial line exceeded {max_line_bytes} bytes before newline"
            )
        complete.append(bytes(pending[:newline + 1]))
        del pending[:newline + 1]
    return complete


def parse_event_record(line: str) -> tuple[dict, bytes] | None:
    match = re.search(
        r"nvs_test_event_record device_id=(\S+) boot_id=(\S+) seq=(\d+) payload=(\{.*\})\s*$",
        line,
    )
    if not match:
        return None
    identity = {"device_id": match.group(1), "boot_id": match.group(2), "seq": int(match.group(3))}
    raw = match.group(4).encode("utf-8")
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError:
        return None
    if (payload.get("device_id"), payload.get("boot_id"), payload.get("seq")) != (
        identity["device_id"], identity["boot_id"], identity["seq"]
    ):
        raise AssertionError("test-only enqueue log identity differs from its serialized payload")
    return identity, raw


class SerialEventRecordAssembler:
    """Reconstruct test-only event JSON sent as short UART records.

    Long Serial.printf output can be interrupted by ESP-IDF reconnect logs from
    the MQTT worker. Indexed chunks let the host ignore those unrelated lines
    while still validating the complete payload and identity before accepting
    it as enqueue evidence.
    """

    _begin = re.compile(
        r"^nvs_test_event_record_begin device_id=(\S+) boot_id=(\S+) seq=(\d+) "
        r"payload_bytes=(\d+) chunks=(\d+)\s*$"
    )
    _chunk = re.compile(
        r"^nvs_test_event_record_chunk device_id=(\S+) boot_id=(\S+) seq=(\d+) "
        r"part=(\d+) data=(.*)$"
    )
    _end = re.compile(
        r"^nvs_test_event_record_end device_id=(\S+) boot_id=(\S+) seq=(\d+) "
        r"chunks=(\d+)\s*$"
    )

    def __init__(self) -> None:
        self._pending: dict[tuple[str, str, int], dict] = {}

    def feed(self, line: str) -> str | None:
        begin = self._begin.match(line)
        if begin:
            identity = (begin.group(1), begin.group(2), int(begin.group(3)))
            payload_bytes, chunks = int(begin.group(4)), int(begin.group(5))
            if not 1 <= chunks <= 1024 or not 1 <= payload_bytes <= MAX_SERIAL_LINE_BYTES:
                raise ValueError("invalid NVS event record chunk bounds")
            if identity in self._pending:
                raise ValueError(f"duplicate NVS event record begin for {identity}")
            self._pending[identity] = {
                "payload_bytes": payload_bytes,
                "chunks": chunks,
                "parts": {},
            }
            return None

        chunk = self._chunk.match(line)
        if chunk:
            identity = (chunk.group(1), chunk.group(2), int(chunk.group(3)))
            record = self._pending.get(identity)
            if record is None:
                return None
            part = int(chunk.group(4))
            if not 0 <= part < record["chunks"]:
                raise ValueError(f"NVS event record part index out of range for {identity}")
            value = chunk.group(5)
            previous = record["parts"].get(part)
            if previous is not None and previous != value:
                raise ValueError(f"conflicting NVS event record chunk for {identity} part={part}")
            record["parts"][part] = value
            return None

        end = self._end.match(line)
        if not end:
            return None
        identity = (end.group(1), end.group(2), int(end.group(3)))
        record = self._pending.pop(identity, None)
        if record is None:
            return None
        if int(end.group(4)) != record["chunks"]:
            raise ValueError(f"NVS event record end count mismatch for {identity}")
        if len(record["parts"]) != record["chunks"]:
            raise ValueError(f"NVS event record is missing chunks for {identity}")
        payload = "".join(record["parts"][index] for index in range(record["chunks"]))
        if len(payload.encode("utf-8")) != record["payload_bytes"]:
            raise ValueError(f"NVS event record byte length mismatch for {identity}")
        reconstructed = (
            f"nvs_test_event_record device_id={identity[0]} boot_id={identity[1]} "
            f"seq={identity[2]} payload={payload}"
        )
        try:
            parsed = parse_event_record(reconstructed)
        except AssertionError as exc:
            raise ValueError(f"NVS event record identity mismatch for {identity}") from exc
        if parsed is None:
            raise ValueError(f"NVS event record payload is invalid for {identity}")
        return reconstructed


def parse_nvs_queue_snapshot(lines: list[str], expected_device_id: str = DEVICE_ID) -> dict:
    """Parse a complete firmware test-only snapshot of every FIFO NVS entry."""
    begin_prefix = "nvs_test_queue_snapshot_begin "
    end_prefix = "nvs_test_queue_snapshot_end "
    begins = [line for line in lines if begin_prefix in line]
    ends = [line for line in lines if end_prefix in line]
    if len(begins) != 1 or len(ends) != 1:
        raise AssertionError("firmware did not return exactly one complete NVS queue snapshot")

    def fields(line: str, marker: str) -> dict[str, str]:
        return dict(re.findall(r"(\w+)=([^\s]+)", line.split(marker, 1)[1]))

    begin = fields(begins[0], begin_prefix)
    end = fields(ends[0], end_prefix)
    if begin.get("device_id") != expected_device_id or end.get("device_id") != expected_device_id:
        raise AssertionError("NVS snapshot belongs to the wrong firmware device")
    if not begin.get("boot_id") or begin.get("boot_id") != end.get("boot_id"):
        raise AssertionError("NVS snapshot begin/end boot identities disagree")
    try:
        queue_count = int(begin["queue_count"])
        end_count = int(end["queue_count"])
        reported_records = int(end["records"])
        head = int(begin["head"])
        capacity = int(begin["capacity"])
    except (KeyError, ValueError) as exc:
        raise AssertionError("NVS snapshot omitted a valid count, head, or capacity") from exc
    if capacity not in (8, 16, 32) or head < 0 or head >= capacity:
        raise AssertionError("NVS snapshot reported an invalid ring capacity or head slot")
    if queue_count < 0 or queue_count > capacity or end_count != queue_count:
        raise AssertionError("NVS snapshot begin/end queue counts disagree or exceed capacity")
    if end.get("outcome") != "complete":
        raise AssertionError(f"firmware marked NVS queue snapshot invalid: {end.get('outcome')}")

    records: list[dict] = []
    seen_identities: set[tuple[str, str, int]] = set()
    record_pattern = re.compile(
        r"nvs_test_queue_record device_id=(\S+) event_boot_id=(\S+) event_seq=(\d+) "
        r"index=(\d+) slot=(\d+) queue_count=(\d+) payload=(\{.*\})\s*$"
    )
    for line in lines:
        if "nvs_test_queue_record " not in line:
            continue
        match = record_pattern.search(line)
        if not match:
            raise AssertionError("firmware returned a malformed or invalid NVS queue record")
        device_id, boot_id, seq_text, index_text, slot_text, count_text, payload_text = match.groups()
        payload = json.loads(payload_text)
        seq, index, slot, record_count = map(int, (seq_text, index_text, slot_text, count_text))
        if not isinstance(payload, dict) or payload.get("kind") != "event" or seq <= 0:
            raise AssertionError("NVS queue snapshot payload is not a valid event record")
        if device_id != expected_device_id or record_count != queue_count:
            raise AssertionError("NVS queue record device or count differs from snapshot header")
        if (payload.get("device_id"), payload.get("boot_id"), payload.get("seq")) != (
            device_id, boot_id, seq
        ):
            raise AssertionError("NVS queue snapshot identity differs from serialized payload")
        if index != len(records) or slot != (head + index) % capacity:
            raise AssertionError("NVS queue snapshot is not in the persisted FIFO slot order")
        identity = (device_id, boot_id, seq)
        if identity in seen_identities:
            raise AssertionError(f"NVS queue snapshot contains duplicate event identity: {identity}")
        seen_identities.add(identity)
        records.append({
            "device_id": device_id, "boot_id": boot_id, "seq": seq,
            "index": index, "slot": slot, "queue_count": record_count,
            "payload": payload_text.encode("utf-8"),
        })
    if len(records) != queue_count or reported_records != queue_count:
        raise AssertionError(
            f"NVS queue snapshot record count mismatch: header={queue_count}, "
            f"records={len(records)}, end={reported_records}"
        )
    return {"device_id": expected_device_id, "boot_id": begin.get("boot_id"),
            "queue_count": queue_count, "records": records}


def validate_event_retained_after_lost_ack(
    snapshot: dict,
    identity: tuple[str, str, int],
    expected_payload: bytes,
) -> int:
    """Confirm a deliberately unacknowledged event remains byte-identical in NVS.

    Queue cardinality can legitimately increase while the gateway commits the
    event (for example, a post-reboot SAFE transition). The identity and payload
    of the event whose ACK was dropped are the persistence contract.
    """
    records = snapshot.get("records")
    if not isinstance(records, list):
        raise AssertionError("NVS snapshot has no record list after dropped application ACK")
    matches = [record for record in records
               if (record.get("device_id"), record.get("boot_id"), record.get("seq")) == identity]
    if not matches:
        raise AssertionError(f"NVS event identity {identity} is missing after dropped application ACK")
    if len(matches) != 1:
        raise AssertionError(f"NVS event identity {identity} is duplicated after dropped application ACK")
    if matches[0].get("payload") != expected_payload:
        raise AssertionError(f"NVS event payload changed after dropped application ACK for {identity}")
    try:
        queue_count = int(snapshot["queue_count"])
    except (KeyError, TypeError, ValueError) as exc:
        raise AssertionError("NVS snapshot omitted a valid queue count after dropped application ACK") from exc
    if queue_count != len(records):
        raise AssertionError("NVS snapshot queue count differs from its records after dropped application ACK")
    return queue_count


def payload_to_bytes(payload: str | bytes | bytearray) -> bytes:
    """Normalize MQTT payload representations without double-encoding bytes."""
    if isinstance(payload, bytes):
        return payload
    if isinstance(payload, bytearray):
        return bytes(payload)
    if isinstance(payload, str):
        return payload.encode("utf-8")
    raise TypeError("MQTT payload must be str, bytes, or bytearray")


def collect_enqueue_records(lines: list[str], start: int = 0) -> dict[tuple[str, str, int], bytes]:
    records: dict[tuple[str, str, int], bytes] = {}
    for line in lines[start:]:
        parsed = parse_event_record(line)
        if not parsed:
            continue
        identity, raw = parsed
        key = (identity["device_id"], identity["boot_id"], identity["seq"])
        if key in records and records[key] != raw:
            raise AssertionError(f"firmware emitted different NVS payloads for one identity: {key}")
        records[key] = raw
    return records


def first_queued_identity(records: dict[tuple[str, str, int], bytes]) -> tuple[str, str, int]:
    """Return the first observed enqueue identity, matching the FIFO queue head."""
    if not records:
        raise AssertionError("cannot determine NVS FIFO head without any observed enqueue record")
    return next(iter(records))


def sensor_fault_event_matches(line: str, sensor: str, other_state: str) -> bool:
    parsed = parse_event_record(line)
    if not parsed:
        return False
    _identity, raw = parsed
    payload = json.loads(raw)
    target = payload.get(sensor.lower(), {})
    other = payload.get("co" if sensor == "LPG" else "lpg", {})
    return (payload.get("state") == "FAULT" and target.get("state") == "FAULT"
            and target.get("valid") is False and other.get("state") == other_state)


def set_sensor_invalid(monitor: "SerialMonitor", sensor: str, invalid: bool) -> dict:
    value = int(invalid)
    expected = f"nvs_test_control outcome=accepted command=set_sensor_invalid sensor={sensor} invalid={value}"
    monitor.send(f"NVS_TEST SET_SENSOR_INVALID {sensor} {value}", lambda item: expected in item)
    status = monitor.status()
    fields = {"LPG": "lpg_invalid_test", "CO": "co_invalid_test"}
    if sensor == "BOTH":
        applied = (status.get(fields["LPG"]) == value and status.get(fields["CO"]) == value)
    else:
        applied = status.get(fields[sensor]) == value
    if not applied:
        raise AssertionError(f"firmware accepted sensor-invalid control but status did not reflect sensor={sensor} invalid={value}")
    return status


def wait_for_fault_output(monitor: "SerialMonitor", timeout: float, description: str) -> dict:
    """Require local red GPIO and nonzero buzzer duty while MQTT is offline."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        status = monitor.status()
        if status["red_pin"] == 1 and status["buzzer_duty"] > 0 and status["mqtt_connected"] == 0:
            return status
        time.sleep(0.05)
    raise TimeoutError(f"timed out waiting for offline FAULT local red/buzzer output: {description}")


class SerialMonitor:
    def __init__(self, url: str, log: RuntimeLog, serial_log: Path,
                 connect_timeout: float = 90, write_timeout: float = 5) -> None:
        try:
            import serial  # type: ignore[import-not-found]
        except ImportError as exc:
            raise Blocked("PySerial is not installed; cannot attach to the Wokwi RFC2217 serial bridge") from exc
        self.log = log
        self.port = open_serial_when_ready(
            serial, url, timeout=connect_timeout, retry_delay=0.5, log=self.log
        )
        self.serial_log = serial_log
        self.lines: list[str] = []
        self._event_record_assembler = SerialEventRecordAssembler()
        self._lock = threading.RLock()
        self._closed = threading.Event()
        self._reader_error: Exception | None = None
        self._event_record_error: ValueError | None = None
        self._write_timeout = write_timeout
        self._reader = threading.Thread(target=self._read_loop, name="nvs-wokwi-serial", daemon=True)
        self._reader.start()

    def _read_loop(self) -> None:
        pending = bytearray()
        try:
            self.serial_log.parent.mkdir(parents=True, exist_ok=True)
            with self.serial_log.open("a", encoding="utf-8") as output:
                while not self._closed.is_set():
                    try:
                        raw = self.port.readline()
                    except Exception as exc:
                        if self._closed.is_set():
                            break
                        self._record_reader_error(exc)
                        break
                    if not raw:
                        continue
                    try:
                        complete_lines = extract_complete_serial_lines(pending, raw)
                    except SerialLineTooLong as exc:
                        self._record_reader_error(exc)
                        break
                    for complete_raw in complete_lines:
                        line = complete_raw.decode("utf-8", errors="replace").strip()
                        if not line:
                            continue
                        with self._lock:
                            self.lines.append(line)
                        output.write(line + "\n")
                        output.flush()
                        self.log.write("firmware_serial", detail=line[:320])
                        try:
                            reconstructed = self._event_record_assembler.feed(line)
                        except ValueError as exc:
                            with self._lock:
                                self._event_record_error = exc
                            self.log.write("serial_event_record_reassembly_error",
                                           error_type=type(exc).__name__, detail=str(exc)[:240])
                            reconstructed = None
                        if reconstructed is not None:
                            parsed = parse_event_record(reconstructed)
                            assert parsed is not None
                            identity, raw_payload = parsed
                            with self._lock:
                                self.lines.append(reconstructed)
                            output.write(reconstructed + "\n")
                            output.flush()
                            self.log.write(
                                "serial_event_record_reassembled",
                                device_id=identity["device_id"],
                                boot_id=identity["boot_id"],
                                seq=identity["seq"],
                                payload_sha256=hashlib.sha256(raw_payload).hexdigest(),
                                detail=f"payload_bytes={len(raw_payload)}",
                            )
        except Exception as exc:
            if not self._closed.is_set():
                self._record_reader_error(exc)

    def _record_reader_error(self, exc: Exception) -> None:
        with self._lock:
            self._reader_error = exc
        self.log.write("serial_read_error", error_type=type(exc).__name__,
                       detail=str(exc)[:240])

    def cursor(self) -> int:
        with self._lock:
            return len(self.lines)

    def wait_line(self, predicate: Callable[[str], bool], timeout: float,
                  description: str, start: int = 0) -> tuple[int, str]:
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            with self._lock:
                if self._event_record_error is not None:
                    raise AssertionError(
                        f"invalid firmware NVS event serial framing: {self._event_record_error}"
                    ) from self._event_record_error
                if self._reader_error is not None:
                    raise SerialTransportBlocked(
                        f"SERIAL_READ_ERROR: {type(self._reader_error).__name__}: {self._reader_error}"
                    ) from self._reader_error
                for index in range(start, len(self.lines)):
                    line = self.lines[index]
                    if predicate(line):
                        return index, line
            time.sleep(0.05)
        raise TimeoutError(f"timed out waiting for firmware serial evidence: {description}")

    def send(self, command: str, response: Callable[[str], bool], timeout: float = 5) -> tuple[int, str]:
        start = self.cursor()
        payload = (command + "\n").encode("ascii")
        outcome: dict[str, Exception] = {}
        completed = threading.Event()

        def write_command() -> None:
            try:
                self.port.write(payload)
                self.port.flush()
            except Exception as exc:
                outcome["error"] = exc
            finally:
                completed.set()

        writer = threading.Thread(target=write_command, name="nvs-serial-write", daemon=True)
        writer.start()
        if not completed.wait(self._write_timeout):
            self.log.write("serial_write_timeout", timeout_seconds=self._write_timeout,
                           detail="closing RFC2217/serial port after application write deadline")
            self.close()
            writer.join(timeout=0.5)
            if writer.is_alive():
                self.log.write("serial_writer_close_timeout", timeout_seconds=0.5,
                               detail="RFC2217 writer remained alive after port close")
            raise SerialWriteTimeout(
                f"SERIAL_WRITE_TIMEOUT: {command!r} exceeded {self._write_timeout:g}s application deadline"
            )
        if "error" in outcome:
            error = outcome["error"]
            raise SerialTransportBlocked(
                f"SERIAL_WRITE_ERROR: {type(error).__name__}: {error}"
            ) from error
        return self.wait_line(response, timeout, command, start)

    def status(self) -> dict:
        _, line = self.send("NVS_TEST STATUS", lambda item: "nvs_test_status " in item)
        result = parse_status(line)
        if result is None:
            raise AssertionError("firmware returned malformed NVS_TEST STATUS")
        return result

    def queue_snapshot(self) -> dict:
        start = self.cursor()
        end_index, _line = self.send(
            "NVS_TEST DUMP_QUEUE",
            lambda item: "nvs_test_queue_snapshot_end " in item,
        )
        with self._lock:
            snapshot_lines = list(self.lines[start:end_index + 1])
        return parse_nvs_queue_snapshot(snapshot_lines)

    def close(self) -> None:
        if self._closed.is_set():
            return
        self._closed.set()
        try:
            self.port.close()
        except Exception as exc:
            self.log.write("serial_close_error", error_type=type(exc).__name__, detail=str(exc)[:240])
        self._reader.join(timeout=2)
        if self._reader.is_alive():
            self.log.write("serial_reader_close_timeout", timeout_seconds=2,
                           detail="serial reader remained alive after bounded join")


def serial_open_options(url: str, baudrate: int = 115200, read_timeout: float = 0.15,
                        write_timeout: float = 2) -> tuple[dict, str, str]:
    """Choose options supported by the actual pySerial URL backend."""
    try:
        parsed = urlsplit(url)
        scheme = parsed.scheme.lower()
    except ValueError as exc:
        raise SerialTransportBlocked(f"SERIAL_URL_INVALID: {exc}") from exc

    options = {"baudrate": baudrate, "timeout": read_timeout}
    if scheme == "rfc2217":
        try:
            host, port = parsed.hostname, parsed.port
        except ValueError as exc:
            raise SerialTransportBlocked(f"RFC2217_URL_INVALID: {exc}") from exc
        if not host or port is None or not (1 <= port <= 65535):
            raise SerialTransportBlocked(
                "RFC2217_URL_INVALID: expected rfc2217://<host>:<port>"
            )
        if parsed.username or parsed.password:
            raise SerialTransportBlocked("RFC2217_URL_INVALID: credentials are not accepted in the serial URL")
        # PySerial 3.5's RFC2217 backend explicitly raises NotImplementedError
        # when write_timeout is set. Writes are bounded in SerialMonitor.send.
        return options, scheme, f"{host}:{port}"

    if scheme:
        raise SerialTransportBlocked(
            f"SERIAL_SCHEME_UNSUPPORTED: {scheme!r}; supported forms are RFC2217 URLs or native serial ports"
        )
    options["write_timeout"] = write_timeout
    return options, "native", url


def _exception_chain(exc: Exception):
    seen: set[int] = set()
    current: BaseException | None = exc
    while current is not None and id(current) not in seen:
        seen.add(id(current))
        yield current
        current = current.__cause__ or current.__context__


def _serial_open_error_kind(exc: Exception) -> tuple[str, bool]:
    chain = list(_exception_chain(exc))
    message = " ".join(str(item).lower() for item in chain)
    if any(isinstance(item, (TypeError, ValueError, NotImplementedError)) for item in chain):
        return "SERIAL_DRIVER_CONFIGURATION_ERROR", False
    if any(isinstance(item, socket.gaierror) for item in chain) or any(
        marker in message for marker in (
            "getaddrinfo failed", "name or service not known", "no such host",
            "temporary failure in name resolution", "no such name",
        )
    ):
        return "SERIAL_HOST_UNRESOLVED", False
    if any(isinstance(item, PermissionError) for item in chain) or any(
        marker in message for marker in ("access is denied", "permission denied", "operation not permitted")
    ):
        return "SERIAL_ACCESS_DENIED", False
    if any(
        marker in message for marker in (
            "does not seem to support rfc2217", "does not accept parameter change",
            "rfc2217 protocol", "unsupported rfc2217",
        )
    ):
        return "RFC2217_PROTOCOL_ERROR", False

    transient_errnos = {
        errno.ECONNREFUSED, errno.ETIMEDOUT, errno.ECONNRESET, errno.ECONNABORTED,
    }
    transient_winerrors = {10053, 10054, 10060, 10061}
    for item in chain:
        item_errno = getattr(item, "errno", None)
        item_winerror = getattr(item, "winerror", None)
        if item_errno in transient_errnos or item_winerror in transient_winerrors:
            if item_errno == errno.ECONNREFUSED or item_winerror == 10061:
                return "RFC2217_ENDPOINT_NOT_OPEN", True
            if item_errno == errno.ETIMEDOUT or item_winerror == 10060:
                return "SERIAL_CONNECT_TIMEOUT", True
            return "SERIAL_CONNECTION_INTERRUPTED", True
    if any(isinstance(item, (ConnectionRefusedError,)) for item in chain) or any(
        marker in message for marker in ("connection refused", "actively refused")
    ):
        return "RFC2217_ENDPOINT_NOT_OPEN", True
    if any(isinstance(item, (socket.timeout, TimeoutError)) for item in chain) or any(
        marker in message for marker in ("timed out", "connection timeout")
    ):
        return "SERIAL_CONNECT_TIMEOUT", True
    if any(isinstance(item, (ConnectionResetError, ConnectionAbortedError)) for item in chain) or any(
        marker in message for marker in ("connection reset", "connection aborted")
    ):
        return "SERIAL_CONNECTION_INTERRUPTED", True

    # PySerial wraps socket connect errors in SerialException. Only retry its
    # known "could not open port" form when no deterministic cause was found.
    if any(type(item).__name__ == "SerialException" for item in chain) and "could not open port" in message:
        return "SERIAL_ENDPOINT_UNAVAILABLE", True
    if any(isinstance(item, OSError) for item in chain):
        return "SERIAL_OPEN_OS_ERROR", False
    return "SERIAL_OPEN_NONTRANSIENT_ERROR", False


def serial_url_with_debug(url: str) -> str:
    """Enable PySerial Telnet negotiation diagnostics without changing the endpoint."""
    try:
        parsed = urlsplit(url)
    except ValueError as exc:
        raise SerialTransportBlocked(f"SERIAL_URL_INVALID: {exc}") from exc
    if parsed.scheme.lower() != "rfc2217":
        return url
    query = parse_qsl(parsed.query, keep_blank_values=True)
    if not any(key.lower() == "logging" for key, _value in query):
        query.append(("logging", "debug"))
    return urlunsplit((parsed.scheme, parsed.netloc, parsed.path, urlencode(query), parsed.fragment))


def open_serial_when_ready(serial_module, url: str, timeout: float = 90,
                           retry_delay: float = 0.5, log: RuntimeLog | None = None):
    """Wait for the newly launched Wokwi RFC2217 endpoint instead of racing it."""
    options, scheme, target = serial_open_options(url)
    started = time.monotonic()
    deadline = started + timeout
    last_error: Exception | None = None
    last_kind = "SERIAL_ENDPOINT_UNAVAILABLE"
    attempts = 0
    last_retry_log = started - 5
    if log:
        log.write("serial_connect_start", scheme=scheme, target=target,
                  timeout_seconds=timeout, options=options)
    while True:
        attempts += 1
        try:
            port = serial_module.serial_for_url(url, **options)
            if log:
                log.write("serial_connect_ok", scheme=scheme, target=target,
                          attempts=attempts, elapsed_ms=round((time.monotonic() - started) * 1000))
            return port
        except Exception as exc:
            kind, retryable = _serial_open_error_kind(exc)
            if not retryable:
                if log:
                    log.write("serial_connect_rejected", scheme=scheme, target=target,
                              attempts=attempts, category=kind, error_type=type(exc).__name__,
                              detail=str(exc)[:320], elapsed_ms=round((time.monotonic() - started) * 1000))
                if kind == "SERIAL_OPEN_NONTRANSIENT_ERROR":
                    raise
                raise SerialTransportBlocked(f"{kind}: {type(exc).__name__}: {exc}") from exc
            last_error = exc
            last_kind = kind
            if time.monotonic() >= deadline:
                break
            now = time.monotonic()
            if log and (attempts == 1 or now - last_retry_log >= 5):
                log.write("serial_connect_retry", scheme=scheme, target=target,
                          attempts=attempts, category=kind, error_type=type(exc).__name__,
                          detail=str(exc)[:240], elapsed_ms=round((now - started) * 1000))
                last_retry_log = now
            time.sleep(min(retry_delay, max(0.0, deadline - time.monotonic())))
    detail = f"; last error={type(last_error).__name__}: {last_error}" if last_error else ""
    if scheme == "rfc2217" and last_kind == "RFC2217_ENDPOINT_NOT_OPEN":
        reason = (f"{last_kind}: no listener accepted RFC2217 at {target}; the local simulator may not be running "
                  f"or its rfc2217ServerPort does not match. Waited {timeout:g}s{detail}")
    else:
        reason = f"{last_kind}: serial endpoint {target} was unavailable for {timeout:g}s{detail}"
    if log:
        log.write("serial_connect_timeout", scheme=scheme, target=target,
                  attempts=attempts, category=last_kind,
                  elapsed_ms=round((time.monotonic() - started) * 1000), detail=reason[:400])
    raise SerialTransportBlocked(reason)


def runtime_failure_classification(exc: Exception) -> tuple[str, int]:
    """Keep missing host/simulator prerequisites distinct from runtime failures."""
    if isinstance(exc, Blocked):
        return "BLOCKED", 77
    return "FAIL", 1


def observe_stable_empty_queue(status_provider: Callable[[], dict], timeout: float = 30,
                               interval: float = 0.25, consecutive: int = 3) -> dict:
    """Require several consecutive online/empty observations before outage injection."""
    deadline = time.monotonic() + timeout
    streak = 0
    while time.monotonic() < deadline:
        latest = status_provider()
        if latest.get("mqtt_connected") == 1 and latest.get("queue_count") == 0:
            streak += 1
            if streak >= consecutive:
                return latest
        else:
            streak = 0
        time.sleep(interval)
    raise TimeoutError("NVS queue did not reach a stable empty baseline while MQTT was connected")


def validate_startup_status(status: dict, expected_device_id: str = DEVICE_ID) -> int:
    """Validate identity while allowing boot-time NVS entries to await gateway startup."""
    actual_device_id = status.get("device_id")
    if actual_device_id != expected_device_id:
        raise AssertionError(f"wrong firmware device_id: {actual_device_id}")
    try:
        queue_count = int(status["queue_count"])
    except (KeyError, TypeError, ValueError) as exc:
        raise AssertionError("firmware startup status did not include a valid NVS queue_count") from exc
    if queue_count < 0:
        raise AssertionError(f"firmware reported a negative startup NVS queue count: {queue_count}")
    return queue_count


def capture_startup_queue_snapshot(monitor: SerialMonitor, log: RuntimeLog,
                                   retries: int = 5) -> tuple[dict, dict]:
    """Take two matching queue dumps before the test broker can ACK any event."""
    for attempt in range(1, retries + 1):
        before = monitor.status()
        if before["mqtt_connected"] != 0:
            raise Blocked("firmware was already MQTT-connected before the isolated test broker started")
        first = monitor.queue_snapshot()
        middle = monitor.status()
        second = monitor.queue_snapshot()
        after = monitor.status()
        first_records = [(row["device_id"], row["boot_id"], row["seq"], row["payload"])
                         for row in first["records"]]
        second_records = [(row["device_id"], row["boot_id"], row["seq"], row["payload"])
                          for row in second["records"]]
        counts = (before["queue_count"], first["queue_count"], middle["queue_count"],
                  second["queue_count"], after["queue_count"])
        boot_ids = (before["boot_id"], middle["boot_id"], after["boot_id"])
        snapshot_boot_ids = (first.get("boot_id"), second.get("boot_id"))
        if (len(set(counts)) == 1 and len(set(boot_ids)) == 1 and
                snapshot_boot_ids == (before["boot_id"], before["boot_id"]) and
                first_records == second_records):
            return after, second
        log.write("startup_queue_snapshot_retry", device_id=after.get("device_id"),
                  boot_id=after.get("boot_id"), seq=after.get("seq"),
                  queue_count=after.get("queue_count"), attempt=attempt,
                  detail=f"unstable queue snapshot counts={counts}; boot_ids={boot_ids}")
        time.sleep(0.15)
    raise AssertionError("could not capture a stable, complete startup NVS queue snapshot before broker startup")


def validate_queue_count_transitions(starting_count: int, serial_lines: list[str],
                                     final_count: int) -> list[tuple[str, str, int]]:
    """Reconcile firmware's persisted queue-count diagnostics over one interval."""
    tracked_count = starting_count
    removals: list[tuple[str, str, int]] = []
    for line in serial_lines:
        item = parse_event_diag(line)
        if not item:
            continue
        if item["stage"] == "enqueue" and item["outcome"] == "stored":
            tracked_count += 1
            if item["queue_count"] != tracked_count:
                raise AssertionError("NVS queue count did not increase by one after a stored event")
        elif item["stage"] == "enqueue" and item["outcome"] == "stored_pointer_write_failed":
            raise AssertionError("event slot was written but its NVS queue pointer commit failed")
        elif item["stage"] == "app_ack" and item["outcome"] == "matched_remove_ok":
            tracked_count -= 1
            if tracked_count < 0 or item["queue_count"] != tracked_count:
                raise AssertionError("NVS queue count did not decrease by exactly one after matched ACK")
            if item["detail"] != "pointers_saved":
                raise AssertionError("NVS removal completed without a persisted queue pointer state")
            removals.append((item["device_id"], item["boot_id"], item["seq"]))
    if tracked_count != final_count:
        raise AssertionError(
            f"diagnostic queue-count accounting disagrees with final status: "
            f"{tracked_count} != {final_count}"
        )
    return removals


def validate_startup_backlog_replay(snapshot: dict, published_events: list[dict],
                                    application_acks: list[dict], sqlite_rows: list[dict],
                                    backend_rows: list[dict], serial_lines: list[str],
                                    starting_cursor: int) -> list[tuple[str, str, int]]:
    """Require each boot-time NVS event to pass publish, durable commit, app ACK, and removal."""
    backlog = snapshot["records"]
    if len(backlog) != snapshot["queue_count"]:
        raise AssertionError("cannot enumerate every event in the startup NVS backlog")
    expected_ids = [(row["device_id"], row["boot_id"], row["seq"]) for row in backlog]
    post_snapshot_lines = serial_lines[starting_cursor:]
    removals = validate_queue_count_transitions(snapshot["queue_count"], post_snapshot_lines, 0)
    if removals[:len(expected_ids)] != expected_ids:
        raise AssertionError(
            f"startup NVS events were not removed in FIFO order: expected={expected_ids}, "
            f"observed={removals}"
        )

    diagnostics = [parse_event_diag(line) for line in post_snapshot_lines]
    for queued in backlog:
        identity = (queued["device_id"], queued["boot_id"], queued["seq"])
        matching_publishes = [event for event in published_events
                              if (event["device_id"], event["boot_id"], event["seq"]) == identity]
        if not matching_publishes:
            raise AssertionError(f"startup NVS event was never published to MQTT: {identity}")
        if any(event["payload"] != queued["payload"] for event in matching_publishes):
            raise AssertionError(f"startup NVS event payload changed during replay: {identity}")

        rows = [row for row in sqlite_rows
                if (row["device_id"], row["boot_id"], row["seq"]) == identity]
        if len(rows) != 1:
            raise AssertionError(f"startup NVS event did not produce exactly one committed SQLite row: {identity}")
        if json.loads(rows[0]["payload"]) != json.loads(queued["payload"]):
            raise AssertionError(f"startup NVS SQLite payload differs from the queued payload: {identity}")

        commits = [row for row in backend_rows if row.get("event") == "sqlite_commit_complete"
                   and (row.get("device_id"), row.get("boot_id"), row.get("seq")) == identity]
        ack_attempts = [row for row in backend_rows if row.get("event") == "application_ack_publish_attempt"
                        and (row.get("device_id"), row.get("boot_id"), row.get("seq")) == identity]
        if not commits or not ack_attempts:
            raise AssertionError(f"startup NVS event is missing SQLite commit or application ACK diagnostics: {identity}")
        commit_times = [datetime.fromisoformat(row["timestamp_utc"]) for row in commits]
        for attempt in ack_attempts:
            ack_time = datetime.fromisoformat(attempt["timestamp_utc"])
            if not any(commit_time <= ack_time for commit_time in commit_times):
                raise AssertionError(f"application ACK attempt preceded SQLite commit for startup event {identity}")

        acks = [ack for ack in application_acks
                if (ack["device_id"], ack["boot_id"], ack["seq"]) == identity
                and not ack["dropped"] and ack["sqlite_rows_at_publish"] == 1]
        if not acks:
            raise AssertionError(f"gateway did not publish a committed application ACK for startup event {identity}")
        all_identity_acks = [ack for ack in application_acks
                             if (ack["device_id"], ack["boot_id"], ack["seq"]) == identity]
        if any(ack["sqlite_rows_at_publish"] != 1 for ack in all_identity_acks):
            raise AssertionError(f"application ACK for startup event was emitted without exactly one SQLite row: {identity}")
        for ack in all_identity_acks:
            ack_time = datetime.fromisoformat(ack["timestamp_utc"])
            if not any(commit_time <= ack_time for commit_time in commit_times):
                raise AssertionError(f"broker observed application ACK before SQLite commit for startup event {identity}")

        receipt_indexes = [index for index, item in enumerate(diagnostics)
                           if item and item["stage"] == "app_ack" and item["outcome"] == "received_by_main"
                           and (item["device_id"], item["boot_id"], item["seq"]) == identity]
        removal_indexes = [index for index, item in enumerate(diagnostics)
                           if item and item["stage"] == "app_ack" and item["outcome"] == "matched_remove_ok"
                           and (item["device_id"], item["boot_id"], item["seq"]) == identity]
        if len(removal_indexes) != 1 or not any(index < removal_indexes[0] for index in receipt_indexes):
            raise AssertionError(f"firmware did not receive and remove exactly the matching startup event ACK: {identity}")
        removal = diagnostics[removal_indexes[0]]
        if removal is None or removal["detail"] != "pointers_saved":
            raise AssertionError(f"startup NVS removal did not persist queue pointers: {identity}")
    return expected_ids


class RuntimeBrokerProtocol:
    """Hooks the existing minimal MQTT broker without synthetic device clients."""

    def __init__(self, harness_module, controller: "RuntimeBroker") -> None:
        parent = self

        class Broker(harness_module.MiniBroker):
            def publish_to_subscribers(self, topic: str, payload: bytes, qos: int) -> None:
                dropped = topic.endswith("/ack") and parent.controller.consume_drop_ack()
                parent.on_publish(topic, payload, qos, dropped=dropped)
                if dropped:
                    return
                super().publish_to_subscribers(topic, payload, qos)

        self.broker = Broker()
        self.controller = controller

    def on_publish(self, topic: str, payload: bytes, qos: int, dropped: bool = False) -> None:
        if topic.endswith("/event"):
            try:
                data = json.loads(payload)
            except (ValueError, UnicodeDecodeError):
                data = {}
            identity = {key: data.get(key) for key in ("device_id", "boot_id", "seq")}
            digest = self.controller.log.payload("firmware_mqtt_event", identity, payload)
            record = {**identity, "payload_sha256": digest, "payload": payload,
                      "state": data.get("state"), "lpg_state": data.get("lpg", {}).get("state"),
                      "qos": qos, "timestamp_utc": utc_now()}
            with self.controller.lock:
                self.controller.published_events.append(record)
            self.controller.log.write("mqtt_firmware_event", device_id=identity["device_id"],
                                      boot_id=identity["boot_id"], seq=identity["seq"],
                                      payload_sha256=digest, state=record["state"], qos=qos)
        elif topic.endswith("/ack"):
            text = payload.decode("ascii", errors="replace")
            boot_id, separator, seq_text = text.partition(":")
            seq = int(seq_text) if separator and seq_text.isdigit() else -1
            rows = self.controller.db_count(DEVICE_ID, boot_id, seq)
            identity = {"device_id": DEVICE_ID, "boot_id": boot_id, "seq": seq}
            record = {**identity, "payload": text, "sqlite_rows_at_publish": rows,
                      "timestamp_utc": utc_now(), "dropped": dropped}
            with self.controller.lock:
                self.controller.application_acks.append(record)
                if dropped:
                    self.controller.last_dropped_ack_identity = (DEVICE_ID, boot_id, seq)
            stage = "application_ack_dropped" if dropped else "application_ack_broker_publish"
            self.controller.log.write(stage, **identity, sqlite_rows_at_publish=rows)
            if rows != 1:
                with self.controller.lock:
                    self.controller.ack_order_violations.append(record)

    def handle_client(self, conn: socket.socket) -> None:
        self.broker.handle_client(conn)

    def close_clients(self) -> None:
        with self.broker.lock:
            clients = list(self.broker.clients.values())
        for client in clients:
            try:
                client["socket"].shutdown(socket.SHUT_RDWR)
            except OSError:
                pass
            try:
                client["socket"].close()
            except OSError:
                pass


class RuntimeBroker:
    def __init__(self, port: int, db_path: Path, log: RuntimeLog, harness_module) -> None:
        self.port = port
        self.db_path = db_path
        self.log = log
        self.lock = threading.RLock()
        self.published_events: list[dict] = []
        self.application_acks: list[dict] = []
        self.ack_order_violations: list[dict] = []
        self.drop_next_ack = False
        self.last_dropped_ack_identity: tuple[str, str, int] | None = None
        self._listener: socket.socket | None = None
        self._accept_thread: threading.Thread | None = None
        self.protocol = RuntimeBrokerProtocol(harness_module, self)
        self._stopping = threading.Event()

    def db_count(self, device_id: str, boot_id: str, seq: int) -> int:
        if seq < 0:
            return 0
        try:
            con = sqlite3.connect(self.db_path, timeout=2)
            try:
                return int(con.execute(
                    "SELECT COUNT(*) FROM messages WHERE device_id=? AND boot_id=? AND seq=? AND kind='event'",
                    (device_id, boot_id, seq),
                ).fetchone()[0])
            finally:
                con.close()
        except sqlite3.Error:
            return 0

    def consume_drop_ack(self) -> bool:
        with self.lock:
            if not self.drop_next_ack:
                return False
            self.drop_next_ack = False
            return True

    def arm_drop_next_ack(self) -> None:
        with self.lock:
            self.drop_next_ack = True
            self.last_dropped_ack_identity = None
        self.log.write("failure_injection_armed", detail="drop_next_application_ack_only")

    def start(self) -> None:
        listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        exclusive = getattr(socket, "SO_EXCLUSIVEADDRUSE", None)
        if exclusive is not None:
            listener.setsockopt(socket.SOL_SOCKET, exclusive, 1)
        listener.bind(("127.0.0.1", self.port))
        listener.listen(16)
        listener.settimeout(0.25)
        self._listener = listener
        self._stopping.clear()
        self._accept_thread = threading.Thread(target=self._accept_loop, name="nvs-test-broker", daemon=True)
        self._accept_thread.start()
        self.log.write("test_broker_online", detail=f"loopback: {self.port}")

    def _accept_loop(self) -> None:
        listener = self._listener
        while listener is not None and not self._stopping.is_set():
            try:
                conn, _address = listener.accept()
            except socket.timeout:
                continue
            except OSError:
                break
            threading.Thread(target=self.protocol.handle_client, args=(conn,), daemon=True).start()

    def stop(self) -> None:
        self._stopping.set()
        listener, self._listener = self._listener, None
        if listener is not None:
            try:
                listener.close()
            except OSError:
                pass
        self.protocol.close_clients()
        if self._accept_thread:
            self._accept_thread.join(timeout=2)
        self.log.write("test_broker_offline", detail=f"loopback: {self.port}")


def load_mqtt_harness():
    path = TOOLS_E2E / "mqtt_ack_harness.py"
    spec = importlib.util.spec_from_file_location("nvs_runtime_mqtt_harness", path)
    if spec is None or spec.loader is None:
        raise Blocked("existing isolated MQTT broker implementation is unavailable")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def read_rows(db_path: Path, device_id: str | None = None,
              boot_id: str | None = None, seq: int | None = None) -> list[dict]:
    con = sqlite3.connect(db_path, timeout=2)
    con.row_factory = sqlite3.Row
    try:
        query = "SELECT device_id,boot_id,seq,kind,state,payload,received_at FROM messages WHERE kind='event'"
        args: list[object] = []
        clauses = []
        if device_id is not None:
            clauses.append("device_id=?")
            args.append(device_id)
        if boot_id is not None:
            clauses.append("boot_id=?")
            args.append(boot_id)
        if seq is not None:
            clauses.append("seq=?")
            args.append(seq)
        if clauses:
            query += " AND " + " AND ".join(clauses)
        query += " ORDER BY rowid"
        return [dict(row) for row in con.execute(query, args).fetchall()]
    finally:
        con.close()


def backend_records(path: Path) -> list[dict]:
    if not path.exists():
        return []
    records = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        try:
            record = json.loads(line)
        except ValueError:
            continue
        if isinstance(record, dict):
            records.append(record)
    return records


def wait_until(predicate: Callable[[], object], timeout: float, description: str) -> object:
    deadline = time.monotonic() + timeout
    last_error = None
    while time.monotonic() < deadline:
        try:
            result = predicate()
            if result:
                return result
        except (OSError, sqlite3.Error) as exc:
            last_error = exc
        time.sleep(0.1)
    suffix = f" ({type(last_error).__name__}: {last_error})" if last_error else ""
    raise TimeoutError(f"timed out waiting for {description}{suffix}")


def run_fault_offline_trigger(monitor: SerialMonitor, log: RuntimeLog, args,
                              offline_event_cursor: int,
                              baseline_cursor: int | None = None) -> tuple[
                                  dict[tuple[str, str, int], bytes],
                                  list[tuple[str, tuple[str, str, int], bytes]], dict
                              ]:
    """Create LPG-only and CO-only FAULT events while the broker is stopped."""
    if baseline_cursor is None:
        baseline_cursor = monitor.cursor()
    _, safe_line = monitor.wait_line(
        lambda line: line.startswith("node1: LPG SAFE ") and ", CO SAFE " in line,
        args.baseline_timeout, "both gas detectors SAFE before fault injection", baseline_cursor,
    )
    log.write("fault_offline_baseline_safe", detail=safe_line)

    def observe_fault(sensor: str, other_state: str) -> tuple[tuple[str, str, int], bytes]:
        index, line = monitor.wait_line(
            lambda item: sensor_fault_event_matches(item, sensor, other_state),
            args.fault_timeout,
            f"NVS enqueue for {sensor} FAULT while broker is offline",
            offline_event_cursor,
        )
        parsed = parse_event_record(line)
        if not parsed:
            raise AssertionError(f"malformed test event record for {sensor} FAULT")
        identity, raw = parsed
        payload = json.loads(raw)
        status = wait_for_fault_output(monitor, args.alarm_timeout,
                                       f"{sensor} FAULT red/buzzer while broker is offline")
        if status["mqtt_connected"] != 0:
            raise AssertionError(f"broker unexpectedly connected during {sensor} FAULT offline capture")
        if status["queue_count"] <= 0:
            raise AssertionError(f"{sensor} FAULT event was logged but NVS queue remained empty")
        log.write("offline_sensor_fault_enqueued", device_id=identity["device_id"],
                  boot_id=identity["boot_id"], seq=identity["seq"],
                  queue_count=status["queue_count"],
                  payload_sha256=hashlib.sha256(raw).hexdigest(),
                  detail=(f"sensor={sensor};other_state={other_state};"+
                          f"red_pin={status['red_pin']};buzzer_duty={status['buzzer_duty']};serial_index={index}"))
        return (identity["device_id"], identity["boot_id"], identity["seq"]), raw

    control_status = set_sensor_invalid(monitor, "LPG", True)
    log.write("sensor_invalid_control", device_id=control_status["device_id"],
              boot_id=control_status["boot_id"], seq=control_status["seq"],
              queue_count=control_status["queue_count"], detail="sensor=LPG invalid=1;test_target_only")
    lpg_fault = observe_fault("LPG", "SAFE")

    recovery_cursor = monitor.cursor()
    control_status = set_sensor_invalid(monitor, "LPG", False)
    log.write("sensor_invalid_control", device_id=control_status["device_id"],
              boot_id=control_status["boot_id"], seq=control_status["seq"],
              queue_count=control_status["queue_count"], detail="sensor=LPG invalid=0;recovery_enabled")
    monitor.wait_line(
        lambda line: line.startswith("node1: LPG WATCH ") and ", CO SAFE " in line,
        args.fault_timeout, "LPG detector recovery to WATCH before CO fault", recovery_cursor,
    )

    control_status = set_sensor_invalid(monitor, "CO", True)
    log.write("sensor_invalid_control", device_id=control_status["device_id"],
              boot_id=control_status["boot_id"], seq=control_status["seq"],
              queue_count=control_status["queue_count"], detail="sensor=CO invalid=1;test_target_only")
    co_fault = observe_fault("CO", "WATCH")

    with monitor._lock:
        serial_lines = list(monitor.lines)
    records = collect_enqueue_records(serial_lines, offline_event_cursor)
    target_events = [("LPG", lpg_fault[0], lpg_fault[1]),
                     ("CO", co_fault[0], co_fault[1])]
    for sensor, identity, raw in target_events:
        if records.get(identity) != raw:
            raise AssertionError(f"offline {sensor} FAULT payload was not present in the firmware enqueue records")
        payload = json.loads(raw)
        target = payload[sensor.lower()]
        if target.get("state") != "FAULT" or target.get("valid") is not False:
            raise AssertionError(f"offline {sensor} event did not preserve invalid sensor FAULT state")
    after_faults = monitor.status()
    if after_faults["mqtt_connected"] != 0:
        raise AssertionError("firmware MQTT reconnected before fault events were snapshotted")
    if after_faults["queue_count"] != len(records):
        raise AssertionError(
            f"fault offline NVS count differs from firmware enqueue records: "
            f"queue={after_faults['queue_count']} records={len(records)}"
        )
    if after_faults["red_pin"] != 1:
        raise AssertionError("CO FAULT did not keep the local red alarm asserted")
    log.write("offline_sensor_fault_queue_verified", device_id=after_faults["device_id"],
              boot_id=after_faults["boot_id"], seq=after_faults["seq"],
              queue_count=after_faults["queue_count"],
              detail="LPG-only and CO-only FAULT identities retained in offline NVS; MQTT remains disconnected")
    return records, target_events, after_faults


def check_database_duplicates(db_path: Path) -> list[tuple]:
    con = sqlite3.connect(db_path, timeout=2)
    try:
        return con.execute(
            "SELECT device_id,boot_id,seq,COUNT(*) FROM messages WHERE kind='event' "
            "GROUP BY device_id,boot_id,seq HAVING COUNT(*)>1"
        ).fetchall()
    finally:
        con.close()


def runtime_phase_sequence(phase: str) -> tuple[str, ...]:
    """Keep the original default phase while allowing one combined session."""
    sequences = {
        "danger": ("danger",),
        "fault-offline": ("fault-offline",),
        "both": ("danger", "fault-offline"),
    }
    try:
        return sequences[phase]
    except KeyError as exc:
        raise ValueError(f"unsupported NVS runtime phase: {phase}") from exc


